"""Measure a cached collision silhouette from the single authored Glaux source.

The head envelope includes every yaw; collision never changes with client animation.
Run after changing the authored mesh, or --check to verify the checked-in profile.
"""
from __future__ import annotations
import argparse
import gzip
import json
import math
from pathlib import Path
from generate_glaux_assets import unpack

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'src/main/java/com/oliver/daedalon/glaux/GlauxShape.java'


def clip(poly, axis, boundary, above):
    result = []
    for a, b in zip(poly, poly[1:] + poly[:1]):
        inside_a = a[axis] >= boundary if above else a[axis] <= boundary
        inside_b = b[axis] >= boundary if above else b[axis] <= boundary
        if inside_a:
            result.append(a)
        if inside_a != inside_b:
            t = (boundary - a[axis]) / (b[axis] - a[axis])
            result.append(tuple(x + (y - x) * t for x, y in zip(a, b)))
    return result


def measure():
    source = json.loads(gzip.decompress((ROOT / 'tools/glaux_mesh_source.json.gz').read_bytes()))
    body = [[] for _ in range(16)]
    radii = [0.] * 16
    pivot = source['pivot']
    for part in source['parts']:
        positions, indices = unpack(part['positions'], 'f'), unpack(part['indices'], 'I')
        moving = part['name'] != 'body'
        for i in range(0, len(indices), 3):
            face = [tuple(positions[index * 3 + j] + (pivot[j] if moving else 0) + (.5 if j != 1 else 0) for j in range(3)) for index in indices[i:i + 3]]
            low, high = min(v[1] for v in face), max(v[1] for v in face)
            for row in range(max(0, int((low - .025) * 8)), min(15, int((high + .025) * 8)) + 1):
                lower, upper = row / 8, (row + 1) / 8
                if moving:
                    if high < lower - .025 or low > upper + .025:
                        continue
                    radii[row] = max(radii[row], *(math.hypot(v[0] - .5 - pivot[0], v[2] - .5 - pivot[2]) + .025 for v in face))
                else:
                    polygon = clip(clip(face, 1, lower, True), 1, upper, False)
                    if polygon:
                        body[row].append(polygon)
    samples = []
    for row, faces in enumerate(body):
        for column in range(6):
            left, right = -.25 + column / 4, column / 4
            points = []
            for face in faces:
                points.extend(clip(clip(face, 0, left, True), 0, right, False))
            radius = radii[row]
            center_x, center_z = .5 + pivot[0], .5 + pivot[2]
            near = max(0., left - center_x, center_x - right)
            if radius > near:
                depth = math.sqrt(radius * radius - near * near)
                points.extend([(max(left, center_x - radius), row / 8, center_z - depth),
                               (min(right, center_x + radius), (row + 1) / 8, center_z + depth)])
            if points:
                samples.append((min(v[0] for v in points) - .002, row / 8, min(v[2] for v in points) - .002,
                              max(v[0] for v in points) + .002, (row + 1) / 8, max(v[2] for v in points) + .002))
    # A few stacked envelopes give vanilla a readable outline. A dense voxel
    # silhouette exposes dozens of internal step edges as a wire cage in shaders.
    boxes = []
    for low, high in [(0, .25), (.25, .5), (.5, .75), (.75, 1), (1, 1.375), (1.375, 1.75), (1.75, 2)]:
        layer = [box for box in samples if low <= box[1] and box[4] <= high]
        if layer:
            boxes.append((min(b[0] for b in layer), low, min(b[2] for b in layer),
                          max(b[3] for b in layer), high, max(b[5] for b in layer)))
    return boxes


def render(boxes):
    rows = '\n'.join('        {' + ', '.join(f'{x:.5f}' for x in box) + '},' for box in boxes)
    return '''package com.oliver.daedalon.glaux;

import net.minecraft.util.math.Direction;
import net.minecraft.util.shape.VoxelShape;
import net.minecraft.util.shape.VoxelShapes;

/** Measured silhouette, generated by tools/generate_glaux_shape.py. */
final class GlauxShape {
    private static final double[][] BOXES = {
''' + rows + '''
    };
    private static final VoxelShape[][] SHAPES = create();
    private GlauxShape() { }
    static VoxelShape get(boolean upper, Direction facing) {
        return SHAPES[upper ? 1 : 0][facing.getHorizontal()];
    }
    private static VoxelShape[][] create() {
        VoxelShape[][] result = new VoxelShape[2][4];
        for (int half = 0; half < 2; half++) {
            for (Direction facing : Direction.Type.HORIZONTAL) {
                VoxelShape shape = VoxelShapes.empty();
                int turns = switch (facing) { case EAST -> 1; case NORTH -> 2; case WEST -> 3; default -> 0; };
                for (double[] box : BOXES) {
                    if (box[1] < half || box[4] > half + 1) continue;
                    double x0 = box[0], z0 = box[2], x1 = box[3], z1 = box[5];
                    for (int step = 0; step < turns; step++) {
                        double previousX0 = x0, previousX1 = x1;
                        x0 = z0; x1 = z1; z0 = 1 - previousX1; z1 = 1 - previousX0;
                    }
                    shape = VoxelShapes.union(shape, VoxelShapes.cuboid(x0, box[1] - half, z0, x1, box[4] - half, z1));
                }
                result[half][facing.getHorizontal()] = shape.simplify();
            }
        }
        return result;
    }
}
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render(measure())
    if args.check:
        assert TARGET.read_text(encoding='utf-8') == text, 'Regenerate Glaux shape after authored geometry changes'
    else:
        TARGET.write_text(text, encoding='utf-8', newline='\n')
    print('Glaux measured collision profile verified' if args.check else 'Glaux measured collision profile generated')
